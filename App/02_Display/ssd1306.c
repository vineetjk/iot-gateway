static uint8_t            fb[SSD1306_W * SSD1306_H / 8];
static uint8_t            cx = 0, cy = 0;
static I2C_HandleTypeDef *hi2c_g;

static void cmd(uint8_t c)
{ uint8_t b[2]={0x00,c}; HAL_I2C_Master_Transmit(hi2c_g,SSD1306_ADDR,b,2,HAL_MAX_DELAY); }

static const uint8_t init_seq[] = {
    0xAE,0xD5,0x80,0xA8,0x1F,0xD3,0x00,0x40,
    0x8D,0x14,0x20,0x00,0xA1,0xC8,0xDA,0x02,
    0x81,0xCF,0xD9,0xF1,0xDB,0x40,0xA4,0xA6,0xAF
};

void SSD1306_Init(I2C_HandleTypeDef *h)
{
    hi2c_g = h;
    HAL_Delay(50);
    for (uint8_t i = 0; i < sizeof(init_seq); i++) cmd(init_seq[i]);
    SSD1306_Clear();
    SSD1306_UpdateScreen();
}

void SSD1306_Clear(void)          { memset(fb, 0, sizeof(fb)); }
void SSD1306_SetCursor(uint8_t x, uint8_t y) { cx=x; cy=y; }

void SSD1306_DrawPixel(uint8_t x, uint8_t y, SSD1306_Color col)
{
    if (x>=SSD1306_W||y>=SSD1306_H) return;
    if (col==White) fb[x+(y/8)*SSD1306_W] |=  (1<<(y%8));
    else            fb[x+(y/8)*SSD1306_W] &= ~(1<<(y%8));
}

static void write_char(char ch, FontDef f, SSD1306_Color col)
{
    if (ch<0x20||ch>0x7E) ch='?';
    const uint8_t *g = f.data + (ch-0x20)*f.w;
    for (uint8_t c=0;c<f.w;c++) {
        uint8_t ln=g[c];
        for (uint8_t r=0;r<f.h;r++)
            SSD1306_DrawPixel(cx+c,cy+r,(ln&(1<<r))?col:(SSD1306_Color)!col);
    }
    cx += f.w;
}

void SSD1306_WriteString(const char *s, FontDef f, SSD1306_Color col)
{ while (*s) write_char(*s++, f, col); }

/* Write string at signed x position (allows negative for scroll clipping) */
void SSD1306_WriteStringAt(int16_t x, uint8_t y, const char *s,
                            FontDef f, SSD1306_Color col)
{
    while (*s) {
        char ch = *s++;
        if (ch < 0x20 || ch > 0x7E) ch = '?';
        if (x + (int16_t)f.w > 0 && x < SSD1306_W) {
            /* At least partially visible */
            const uint8_t *g = f.data + (ch - 0x20) * f.w;
            for (uint8_t c = 0; c < f.w; c++) {
                int16_t px = x + c;
                if (px < 0 || px >= SSD1306_W) continue;
                uint8_t ln = g[c];
                for (uint8_t r = 0; r < f.h; r++)
                    SSD1306_DrawPixel((uint8_t)px, y + r,
                                      (ln & (1 << r)) ? col : (SSD1306_Color)!col);
            }
        }
        x += f.w;
        if (x >= SSD1306_W) break;  /* rest is off-screen right */
    }
}

