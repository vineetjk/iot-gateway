/* Write large-font string (only handles 0-9, '.', '-', ' ') */
static void write_large_char(int16_t x, uint8_t y, char ch, SSD1306_Color col)
{
    uint8_t idx;
    if (ch >= '0' && ch <= '9')      idx = ch - '0';
    else if (ch == '.')              idx = 10;
    else if (ch == '-')              idx = 11;
    else                             idx = 12; /* space */

    const uint8_t *g = font12x16_data + idx * 24; /* 12 cols × 2 bytes */
    for (uint8_t c = 0; c < 12; c++) {
        int16_t px = x + c;
        if (px < 0 || px >= SSD1306_W) continue;
        uint16_t col_data = g[c * 2] | ((uint16_t)g[c * 2 + 1] << 8);
        for (uint8_t r = 0; r < 16; r++) {
            uint8_t py = y + r;
            if (py >= SSD1306_H) break;
            SSD1306_DrawPixel((uint8_t)px, py,
                              (col_data & (1 << r)) ? col : Black);
        }
    }
}

void SSD1306_WriteLargeString(int16_t x, uint8_t y, const char *s, SSD1306_Color col)
{
    while (*s) {
        if (x + 12 > 0 && x < SSD1306_W)
            write_large_char(x, y, *s, col);
        x += 12;
        s++;
        if (x >= SSD1306_W) break;
    }
}

/* Drawing primitives */
void SSD1306_DrawHLine(uint8_t x, uint8_t y, uint8_t w, SSD1306_Color col)
{ for (uint8_t i = 0; i < w; i++) SSD1306_DrawPixel(x + i, y, col); }

void SSD1306_DrawRect(uint8_t x, uint8_t y, uint8_t w, uint8_t h, SSD1306_Color col)
{
    SSD1306_DrawHLine(x, y, w, col);
    SSD1306_DrawHLine(x, y + h - 1, w, col);
    for (uint8_t i = 0; i < h; i++) {
        SSD1306_DrawPixel(x, y + i, col);
        SSD1306_DrawPixel(x + w - 1, y + i, col);
    }
}

void SSD1306_FillRect(uint8_t x, uint8_t y, uint8_t w, uint8_t h, SSD1306_Color col)
{
    for (uint8_t j = 0; j < h; j++)
        for (uint8_t i = 0; i < w; i++)
            SSD1306_DrawPixel(x + i, y + j, col);
}

void SSD1306_InvertScreen(void)
{
    for (uint16_t i = 0; i < sizeof(fb); i++)
        fb[i] = ~fb[i];
}

void SSD1306_DrawBitmap(uint8_t x, uint8_t y, uint8_t w, uint8_t h,
                         const uint8_t *data, SSD1306_Color col)
{
    for (uint8_t j = 0; j < h; j++)
        for (uint8_t i = 0; i < w; i++) {
            uint16_t bit = j * w + i;
            if (data[bit / 8] & (1 << (7 - (bit % 8))))
                SSD1306_DrawPixel(x + i, y + j, col);
        }
}

void SSD1306_UpdateScreen(void)
{
    cmd(0x21); cmd(0); cmd(127);
    cmd(0x22); cmd(0); cmd(3);
    uint8_t *p = fb;
    for (uint16_t i = 0; i < sizeof(fb); i+=16) {
        uint8_t buf[17]; buf[0]=0x40;
        memcpy(buf+1, p+i, 16);
        HAL_I2C_Master_Transmit(hi2c_g, SSD1306_ADDR, buf, 17, HAL_MAX_DELAY);
    }
}
